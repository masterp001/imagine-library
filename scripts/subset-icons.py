"""Subset Material Symbols Rounded to the icons listed in scripts/icons.txt.

Writes src/assets/symbols-rounded.woff2 and src/lib/icons.ts (name -> codepoint).
Run:  python3 scripts/subset-icons.py   (needs: pip install fonttools brotli)
"""
import pathlib
from fontTools.ttLib import TTFont
from fontTools import subset

root = pathlib.Path(__file__).resolve().parent.parent
src_font = root / 'node_modules/material-symbols/material-symbols-rounded.woff2'
names = [n.strip() for n in (root / 'scripts/icons.txt').read_text().split() if n.strip()]

font = TTFont(src_font)
rev = {}
for cp, g in font.getBestCmap().items():
    rev.setdefault(g, cp)
missing = [n for n in names if n not in rev]
if missing:
    raise SystemExit(f'unknown icons: {missing}')
order = set(font.getGlyphOrder())
glyphs = [n for n in names] + [n + '.fill' for n in names if n + '.fill' in order]

opts = subset.Options()
opts.flavor = 'woff2'
opts.layout_features = ['*']
opts.notdef_outline = True
opts.name_IDs = ['*']
sub = subset.Subsetter(opts)
sub.populate(unicodes=[rev[n] for n in names], glyphs=glyphs)
sub.subset(font)
out = root / 'src/assets/symbols-rounded.woff2'
out.parent.mkdir(parents=True, exist_ok=True)
font.save(out)

lines = ['// GENERATED by scripts/subset-icons.py — edit scripts/icons.txt instead.',
         'export const ICONS = {']
lines += [f"  {n}: 0x{rev[n]:x}," for n in names]
lines += ['} as const;', '', 'export type IconName = keyof typeof ICONS;', '']
(root / 'src/lib/icons.ts').write_text('\n'.join(lines))
print(f'{len(names)} icons -> {out} ({out.stat().st_size // 1024} KB)')
